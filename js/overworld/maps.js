// オーバーワールド（地図）のデータ。1 文字 = 1 マス（16px）。
//
// 地形：. 地面  , 地面（色ちがい）  ~ 水（テーマによって 空・マグマ・宇宙）  ^ 山・岩  T 木  * 飾り  B 建物
// 道  ：- 横  | 縦  + 曲がり角（となりの道とつながる向きだけ）
// 点  ：nodes に書いた文字（数字・英字）。点どうしは道でつながり、点が分かれ道になる
//
// 道は、両はしの点のどちらかが「開いている」と通れる（＝表示される）：
//   start（はじめの家）・entry（ワールドの入口）・クリアしたステージ
// まだ無いステージ（STAGES に無い id）は「準備中」になり、入れず、その先の道も開かない。
//
// 隠しコース（H）：{ hidden: true, from: '3' } のように、どのステージのひみつのゴールで開くかを書く。
//   H につながる道は、from のステージを「ひみつのゴール」でクリアした時（記録は '1-3*'）か、H をクリアした時だけ開く。
//   from のステージは地図で赤い点になる（SMW と同じく、もう 1 つの出口がある印）。
// ワールドやステージを足す時は、ここに地図を書き、js/stages/index.js にステージを足すだけでよい。

export const OW_START = { map: 'w1', node: 'S' };

// 地図の並び（「ワールド○」の番号もこの順）
export const OW_ORDER = ['w1', 'w2', 'w3', 'w4', 'w5', 'w6', 'w7', 'w8', 'ex'];

// ワールド k の 1〜4 番とお城（k-5）、前後のワールドへのワープ
// secretFrom：隠しコース（k-S）に行けるひみつのゴールがあるステージの点
const world = (k, name, theme, rows, extra = {}, secretFrom = null) => ({
  name, theme, rows,
  nodes: {
    '1': { stage: `${k}-1` }, '2': { stage: `${k}-2` }, '3': { stage: `${k}-3` }, '4': { stage: `${k}-4` },
    C: { stage: `${k}-5`, castle: true },
    // 隠しコース（ワールドに 1 つ）
    ...(secretFrom ? { H: { stage: `${k}-S`, hidden: true, from: secretFrom, label: `${k}-? ひみつのコース` } } : {}),
    ...(k > 1 ? { P: { warp: `w${k - 1}`, at: 'N', entry: true, label: `ワールド${k - 1}へ` } } : {}),
    ...(k < 8 ? { N: { warp: `w${k + 1}`, at: 'P', label: `ワールド${k + 1}へ` } } : {}),
    ...extra,
  },
});

